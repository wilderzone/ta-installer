// Read the content of the local manifest file.
func readManifest(logger *Logger, root string) (Manifest, error) {
	manifest := Manifest{}
	source := filepath.Join(root, MANIFEST_NAME)
	logger.log(READING_LOCAL_MANIFEST, source)
	file, err := os.OpenFile(source, os.O_RDONLY, os.FileMode(0777))
	if err != nil {
		return manifest, fmt.Errorf("open manifest %s: %w", source, err)
	}
	defer file.Close()

	err = json.NewDecoder(file).Decode(&manifest)
	if err != nil {
		return manifest, fmt.Errorf("decode manifest %s: %w", source, err)
	}

	return manifest, nil
}

// Retrieve a manifest file from the given repo URL.
func getManifest(ctx context.Context, logger *Logger, repo string) (Manifest, error) {
	manifest := Manifest{}
	source, err := url.JoinPath(repo, MANIFEST_NAME)
	if err != nil {
		return manifest, fmt.Errorf("build manifest URL: %w", err)
	}

	logger.log(DOWNLOADING_MANIFEST, source)
	response, err := get(ctx, source)
	if err != nil {
		return manifest, err
	}
	defer response.Body.Close()

	err = json.NewDecoder(response.Body).Decode(&manifest)
	if err != nil {
		return manifest, fmt.Errorf("decode manifest from %s: %w", source, err)
	}

	return manifest, nil
}

// Handle the "asset" command.
func GenerateAssetFile(logger *Logger, arguments arguments) error {
	// Create the asset.
	asset, err := assets.CreateAsset(arguments.path, arguments.name)
	if err != nil {
		return userErrorf(err, "Couldn't read the files in %s to build the asset.", arguments.path)
	}

	// Create the archive.
	archive, size, err := compressAsset(arguments.path, arguments.name)
	if err != nil {
		return userErrorf(err, "Couldn't create the asset archive at %s.", archive)
	}
	asset.PackedSize = size

	// Create the JSON file.
	parent := filepath.Dir(arguments.path)
	path := filepath.Join(parent, arguments.name + ".json")
	file, err := os.Create(path)
	if err != nil {
		return userErrorf(err, "Couldn't create the asset file at %s.", path)
	}
	defer file.Close()
	encoder := json.NewEncoder(file)
	encoder.SetIndent("", "\t")
	err = encoder.Encode(asset)
	if err != nil {
		return userErrorf(err, "Couldn't write the asset file at %s.", path)
	}

	message := fmt.Sprintf("Created asset containing %d %s:", len(asset.Files), logger.plural(len(asset.Files), "file", "files"))
	message += fmt.Sprintf("\n  %s", path)
	message += fmt.Sprintf("\n  %s", archive)
	if size == 0 {
		message += "\nThe packed size needs to be entered manually."
	}
	logger.log(ASSET_CREATED, message)
	return nil
}

// compressAsset creates a zip file containing all files in the provided path.
// The zip file is created in the parent directory of path.
// Returns the full path and size of the zip file.
func compressAsset(path string, name string) (string, uint64, error) {
	parent := filepath.Dir(path)
	destination := filepath.Join(parent, name + ".zip")
	file, err := os.Create(destination)
	if err != nil {
		return destination, 0, err
	}
	defer file.Close()

	directory := os.DirFS(path)
	writer := zip.NewWriter(file)
	err = writer.AddFS(directory)
	if err != nil {
		return destination, 0, err
	}
	writer.Close()

	info, err := file.Stat()
	if err == nil {
		size := info.Size()
		return destination, uint64(size), nil
	}

	// The file size is not critical, so don't return stat errors.
	return destination, 0, nil
}

// Handle the "manifest" command.
func GenerateManifestFile(logger *Logger, arguments arguments) error {
	manifest, err := assets.CreateManifest(arguments.path)
	if err != nil {
		return userErrorf(err, "Couldn't read the asset files in %s to build the manifest.", arguments.path)
	}
	// Catch a broken dependency graph here, rather than mid-install.
	err = assets.ValidateDependencies(manifest.Assets)
	if err != nil {
		return userErrorf(err, "The asset files in %s have a dependency problem: %s", arguments.path, err.Error())
	}
	path := filepath.Join(arguments.path, MANIFEST_NAME)
	file, err := os.Create(path)
	if err != nil {
		return userErrorf(err, "Couldn't create the manifest file at %s.", path)
	}
	defer file.Close()
	encoder := json.NewEncoder(file)
	encoder.SetIndent("", "\t")
	err = encoder.Encode(manifest)
	if err != nil {
		return userErrorf(err, "Couldn't write the manifest file at %s.", path)
	}
	message := fmt.Sprintf("Created manifest containing %d %s: %s", len(manifest.Assets), logger.plural(len(manifest.Assets), "asset", "assets"), path)
	logger.log(MANIFEST_CREATED, message)
	return nil
}

// getPublishedAsset fetches a package's checksum file from the given repo and returns it as
// an Asset ready to verify against the installed files.
//
// It serves the packages that live outside the manifest (the installation utilities and the
// compatibility runtime) whose checksums can't be compiled into TAI. The published file
// (generated by the `asset` command at release time) carries only names and checksums, so the
// Source and Destination - which the caller needs to re-download the package - are filled in
// from the template the caller already knows.
func getPublishedAsset(ctx context.Context, repo string, checksums string, template Asset) (Asset, error) {
	asset := Asset{}
	source, err := url.JoinPath(repo, checksums)
	if err != nil {
		return asset, fmt.Errorf("build checksums URL for %s: %w", template.Name, err)
	}

	response, err := get(ctx, source)
	if err != nil {
		return asset, err
	}
	defer response.Body.Close()

	err = json.NewDecoder(response.Body).Decode(&asset)
	if err != nil {
		return asset, fmt.Errorf("decode checksums from %s: %w", source, err)
	}

	asset.Name = template.Name
	asset.Source = template.Source
	asset.Destination = template.Destination
	return asset, nil
}

// Save a manifest file to disk.
func storeManifest(manifest Manifest, root string) (Manifest, error) {
	destination := filepath.Join(root, MANIFEST_NAME)
	file, err := os.Create(destination)
	if err != nil {
		return manifest, fmt.Errorf("create manifest %s: %w", destination, err)
	}
	defer file.Close()

	encoder := json.NewEncoder(file)
	encoder.SetIndent("", "\t")
	err = encoder.Encode(manifest)
	if err != nil {
		return manifest, fmt.Errorf("encode manifest %s: %w", destination, err)
	}

	return manifest, nil
}
